"""Regenerates docs/TOOLS.md from the contract snapshot so the inventory never drifts from the code."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
snap = json.loads((ROOT / "tests/contract/snapshots/tools.json").read_text(encoding="utf-8"))
AUTH = {"portfolio": "Bearer service token (HTTP) / local stdio", "marketplace": "Bearer service token; per-user GigSim token or Upwork OAuth token (encrypted)",
        "workspace": "Bearer service token (HTTP) / local stdio"}
rows = []
for key, s in sorted(snap.items()):
    server, tool = key.split(".")
    a = s["annotations"]
    rw = "read" if a.get("readOnlyHint") else "write"
    ann = ", ".join(f"{k}={str(v).lower()}" for k, v in a.items() if k.endswith("Hint"))
    extra = []
    props = s["input"].get("properties", {})
    if "idempotency_key" in props:
        extra.append("idempotency key")
    if "dry_run" in props:
        extra.append("dry_run")
    rows.append(f"| `{tool}` | {server} | {rw} | {ann} | {AUTH[server]} | {', '.join(extra) or '-'} |")

text = f"""# MCP Tool Inventory

Generated by `python -m scripts.gen_tools_md` from `tests/contract/snapshots/tools.json`
(the CI schema snapshot), so this table always matches the deployed signatures.

## GigBid's own servers ({len(rows)} tools)

| Tool | Server | Read/Write | Annotations | Auth | Safety |
|---|---|---|---|---|---|
""" + "\n".join(rows) + """

Resources (portfolio): `portfolio://case/{case_id}`, `portfolio://proposal/{proposal_id}`,
`portfolio://evidence/{evidence_id}`, `portfolio://index`.
Prompts (portfolio): `answer_screening_question`, `fit_check`, `case_study_from_project`.

Every call to our servers is rate limited per user (marketplace: 40/min, under GigSim's 60/min),
written to the append-only `audit_log` (user, tool, PII-masked arguments and result, trace id).

## Per-agent allowlists (A6)

Agents receive only the tools named in `agent/config.yaml -> agents` (filtered by name in
`agent/mcp_client.py`); e.g. the Writer can call `search_evidence`/`get_case_study` but has no
marketplace write tool, and only the approval step holds `create_proposal_draft`/`submit_proposal`.

## Third-party servers (A5)

| Server | Used for | Transport / auth | Trust rationale |
|---|---|---|---|
| Upwork official MCP (`https://mcp.upwork.com/mcp`) | live-mode job search, proposal and message **drafts** | Streamable HTTP, OAuth 2.1 + PKCE, tokens Fernet-encrypted per user | Operated by the platform itself, so it is the only sanctioned automation path; every write is a draft the user confirms on Upwork. |
| GitHub official MCP (`github/github-mcp-server`, hosted at `https://api.githubcopilot.com/mcp/`) | ingesting the user's repos (README + code) into the portfolio | Streamable HTTP (or docker stdio), fine-grained read-only PAT | Maintained by GitHub; we grant a read-only token and only call `search_repositories` / `get_file_contents`, so a compromise cannot write to repos. |
"""
(ROOT / "docs" / "TOOLS.md").write_text(text, encoding="utf-8", newline="\n")
print("docs/TOOLS.md:", len(rows), "tools")
